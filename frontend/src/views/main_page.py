
import streamlit as st

def render() -> None:
    """
    Отрисовывает исключительно контентную часть главной страницы.
    """
    st.subheader("🧠 Добро пожаловать в веб-лабораторию «Statistic-Experiments»!")

    st.markdown("""
        Наша интуиция часто нас подводит, когда дело касается вероятностей. То, что кажется нам 
        очевидным, с точки зрения математики часто оказывается ошибкой. 

        Этот проект создан для того, чтобы вы могли **лично проверить знаменитые математические парадоксы**. 
        Вместо того чтобы верить формулам на слово, вы можете запустить симуляции на тысячи и миллионы 
        экспериментов и увидеть, как сухие законы статистики работают в реальном времени!
        """)

    st.markdown("---")

    # Краткий анонс экспериментов
    st.markdown("### 🔬 Какие эксперименты вас ждут?")
    col1, col2 = st.columns(2)

    with col1:
        st.markdown("""
            #### 🚪 Парадокс Монти Холла
            Перед вами 3 двери: за одной автомобиль, за двумя другими — козы. Вы выбираете дверь. 
            Ведущий открывает одну из оставшихся дверей с козой и предлагает изменить выбор.
            * **Вопрос:** Стоит ли менять решение? Увеличит ли это шансы на победу?
            """)

    with col2:
        st.markdown("""
            #### 🎂 Парадокс дней рождения
            Какова вероятность того, что в группе из 23 человек у двоих совпадет день рождения? 
            Математика доказывает, что она выше 50%! 
            * **Правильный ответ:** Всего 23 человека! Кажется невероятным?
            """)

    st.markdown("---")

    # Инструкция
    st.markdown("### 🚀 Как запустить свой первый эксперимент?")
    st.markdown("""
        1. Посмотрите на левую панель **«Выбор эксперимента»**.
        2. В выпадающем списке выберите интересующий вас парадокс.
        3. Настройте параметры симуляции в появившейся форме.
        4. Нажмите кнопку **«Симуляция»**, бэкенд мгновенно всё посчитает!
        """)
